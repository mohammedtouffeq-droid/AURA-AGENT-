def list_all_ultra_capabilities() -> Dict[str, Any]:
    pillars_out: List[Dict[str, Any]] = []
    flat: List[Dict[str, Any]] = []
    idx = 0
    for p in PILLARS:
        p_items = []
        for cid, name, desc, action in p["items"]:
            idx += 1
            entry = {
                "index": idx,
                "id": cid,
                "pillar_id": p["id"],
                "pillar_num": p["num"],
                "pillar_title": p["title"],
                "name": name,
                "description": desc,
                "action": action,
                "accent": p["accent"],
                "tier_required": "tier_5",
            }
            p_items.append(entry)
            flat.append(entry)
        pillars_out.append({
            "id": p["id"],
            "num": p["num"],
            "title": p["title"],
            "subtitle": p["subtitle"],
            "accent": p["accent"],
            "count": len(p_items),
            "items": p_items,
        })
    return {
        "total_count": len(flat),
        "pillars_count": len(pillars_out),
        "pillars": pillars_out,
        "capabilities": flat,
    }


def get_capability_by_id(cap_id: str) -> Optional[Dict[str, Any]]:
    cid = str(cap_id or "").strip().lower()
    for item in list_all_ultra_capabilities()["capabilities"]:
        if item["id"] == cid:
            return item
    return None
